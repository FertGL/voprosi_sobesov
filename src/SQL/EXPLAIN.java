package SQL;

public class EXPLAIN {
    /*
    Когда выполняете какой-нибудь запрос SQL пытается придумать
    оптимальный план выполнения запроса, можно посмотреть этот план используя
    ключевое слово EXPLAIN перед SELECT

    EXPLAIN SELECT * FROM city

    EXPLAIN — это команда в PostgreSQL, которая показывает план выполнения SQL-запроса,
    не выполняя сам запрос.
    Это основной инструмент для оптимизации и анализа производительности запросов.

    EXPLAIN SELECT * FROM users WHERE age > 25;
        Вывод будет примерно таким:


        Seq Scan on users  (cost=0.00..155.00 rows=5000 width=44)
        Filter: (age > 25)

        Расшифровка:

        Seq Scan — последовательное сканирование таблицы
        cost=0.00..155.00 — оценка стоимости (стартовая..общая)
        rows=5000 — ожидаемое количество строк
        width=44 — средний размер строки в байтах


        EXPLAIN ANALYZE — выполнить и показать статистику

        EXPLAIN ANALYZE SELECT * FROM users WHERE email = 'test@example.com';

            Отличия от простого EXPLAIN:
            Фактически выполняет запрос
            Показывает реальное время выполнения
            Добавляет фактические vs планируемые данные

             Если запрос выполняется дольше 100ms(Execution time) и возвращает мало строк
             — где-то есть проблема с доступом к данным (скорее всего, не хватает индексов)

             EXPLAIN (ANALYZE, BUFFERS, FORMAT YAML)
            SELECT * FROM your_query;

            -- Сразу смотрим:
            -- 1. "Execution Time" - общее время
            -- 2. "Plan" -> "Plans" - ищем Seq Scan
            -- 3. Сравниваем "Plan Rows" vs "Actual Rows"
            -- 4. Проверяем "Shared Hit Blocks" vs "Shared Read Blocks"
            --    (много Read Blocks = много чтения с диска)

            1. Парсинг и анализ
            SQL запрос преобразуется в дерево разбора (Parse Tree)
            Проверяется синтаксис, существование объектов, права доступа

            Пример: SELECT * FROM users WHERE id = 1 → Parse Tree
            с элементами SELECT, FROM, WHERE

            2. Переписывание (Rewriting)
            Применяются правила и преобразования:
            Раскрытие VIEW в подзапросы
            Применение RULES (если определены)
            Обработка наследования таблиц

            Пример: VIEW active_users заменяется на SELECT * FROM users WHERE active = true

            3. Планирование (самый сложный этап)
            Планировщик выполняет три ключевые задачи:

            A. Генерация путей доступа для каждой таблицы:
            sql
            -- Для: SELECT * FROM users WHERE age > 25
            Варианты:

            1. Seq Scan (полное сканирование)
            2. Index Scan по индексу age (если есть)
            3. Bitmap Index Scan (комбинация индексов)

            B. Оценка стоимости каждого пути на основе:
            seq_page_cost, random_page_cost, cpu_tuple_cost

            Статистики таблиц (pg_stats)
            Селективности условий (сколько строк отфильтруется)

            C. Выбор JOIN алгоритмов и их порядка:
            Nested Loop: для маленьких таблиц
            Hash Join: для средних, требует построения хеш-таблицы
            Merge Join: для больших отсортированных данных


            4. Оптимизации
            Predicate Pushdown: проталкивание условий WHERE вглубь плана
            Join Reordering: перестановка JOIN для минимизации стоимости
            Subquery to JOIN: преобразование подзапросов
            Итог: Выбирается план с минимальной расчетной стоимостью

     */
}
