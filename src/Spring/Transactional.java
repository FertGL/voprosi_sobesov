package Spring;

public class Transactional {
    /*
    --------------------------------!!!PROXY!!!-------------------------
    Proxy в контексте Java Spring — это объект, который выступает посредником между
    клиентом и целевым объектом (бином), перехватывая вызовы методов для добавления
    дополнительной функциональности (например, транзакций, безопасности, логирования)
    без изменения кода самого бина.

    Spring интенсивно использует прокси для реализации ключевых возможностей
    Аспектно-Ориентированного Программирования (AOP). Когда вы помечаете метод аннотацией
    @Transactional, @Cacheable или @Secured, Spring не изменяет код вашего класса.
    Вместо этого он создает прокси-объект, который оборачивает ваш оригинальный бин.
    Когда вы вызываете метод у бина, полученного из контекста Spring,
    вы на самом деле дергаете метод прокси. Прокси выполняет свою работу (начинает транзакцию,
    проверяет права доступа, достает данные из кэша), а затем (и если нужно)
    вызывает оригинальный метод вашего класса.

    --------------------------------!!!Transactional!!!---------------------------------
    (Он же Dinamic proxy), тк прокси создается во время рантайма
    Spring создает прокси-объект для вашего бина. Когда вы вызываете метод,
    помеченный @Transactional, вызов сначала перехватывается прокси.
    Он открывает транзакцию, затем вызывает ваш оригинальный метод, и после его завершения
    (в зависимости от результата) либо фиксирует изменения (commit),
    либо откатывает их (rollback).

    1. propagation (Распространение транзакции)
    Определяет, как метод должен взаимодействовать с уже существующей транзакцией.

    REQUIRED  --  (по умолчанию)  Если транзакция уже есть — использует её.
    Если нет — создаёт новую . (норм если вызываем транзакционный метод внутри метода
    без транзакции, но нужно явно указать)

    REQUIRES_NEW --	Всегда создаёт новую, независимую транзакцию,
    приостанавливая текущую на время выполнения метода. (норм в случает когда транзакционный
    метод вызывается внутри другого транзакционного метода)

    MANDATORY	Транзакция обязана уже существовать, иначе будет выброшено исключение .

    SUPPORTS	Если транзакция есть — работает в ней, если нет — работает вне транзакции .

    NOT_SUPPORTED	Всегда работает вне транзакции, приостанавливая текущую, если она есть.

    NEVER	Гарантированно требует отсутствия транзакции, иначе выбрасывает исключение.

    NESTED	Выполняется во вложенной транзакции (с использованием точек сохранения, savepoints).
     Позволяет откатить только часть операций внутри основной транзакции .


    2. isolation (Уровень изоляции)
    Определяет, как изменения, сделанные в этой транзакции, будут видны другим параллельно
    выполняющимся транзакциям. Это важно для баланса между согласованностью данных и
    производительностью .

    Уровень	Феномен	Описание
    DEFAULT	-	Используется уровень изоляции, заданный в базе данных по умолчанию.

    READ_UNCOMMITTED -- Грязное чтение -- Транзакция может видеть незафиксированные
                                          изменения других транзакций .

    READ_COMMITTED --	Неповторяющееся чтение -- Защищает от грязного чтения (стандарт в PostgreSQL,
                                                    часто используется в Java-мире) .

    REPEATABLE_READ -- Фантомное чтение -- Гарантирует, что повторное чтение тех же строк в
                                            транзакции даст тот же результат .

    SERIALIZABLE -- Все феномены -- Самый строгий уровень, транзакции выполняются так,
                                        как будто они идут строго друг за другом .


     Важно: Параметры isolation и timeout применяются только к новым транзакциям,
     то есть при использовании Propagation.REQUIRED или Propagation.REQUIRES_NEW .

    3. timeout (Таймаут)
    Максимальное время (в секундах), отведенное на выполнение транзакции.
    Если метод выполняется дольше, транзакция автоматически откатывается.
    Значение по умолчанию (-1) означает использование системного таймаута .

    4. readOnly (Только для чтения)
    Флаг, оптимизирующий транзакцию, если она не вносит изменений в данные.
    @Transactional(readOnly = true) .

    5. rollbackFor / noRollbackFor (Правила отката)
    Задают, при каких исключениях транзакция должна откатываться, а при каких — нет .

    Поведение по умолчанию: Транзакция откатывается только при возникновении непроверяемых
    исключений (RuntimeException и Error). Проверяемые исключения
    (Exception, кроме RuntimeException) не вызывают откат .

    rollbackFor = Exception.class — заставит транзакцию откатываться при любом исключении .

    noRollbackFor = {EntityExistsException.class} — даже если произойдет это исключение,
    транзакция всё равно закоммитится (если не было других ошибок).
     */
}
