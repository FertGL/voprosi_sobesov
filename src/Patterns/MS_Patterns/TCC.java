package Patterns.MS_Patterns;

public class TCC {
    /*
    TCC (Try-Confirm-Cancel) — это паттерн распределённых транзакций для обеспечения согласованности
    данных в микросервисах. В отличие от ACID-транзакций (блокировка БД),
    TCC использует компенсирующие операции, что критически важно для high-load систем.

    Три фазы паттерна

    · Try (Попытка) — резервирование ресурсов. Проверяются условия и блокируются данные для будущего
      изменения (например, помечается товар «в резерве»).
      Если хоть один участник вернул ошибку — выполняется Cancel у всех успешных.
    · Confirm (Подтверждение) — безусловное выполнение операции (списание резерва).
      Считается, что на этом этапе ошибок быть не должно, поэтому логика должна быть идемпотентной.
    · Cancel (Отмена) — откат изменений (освобождение резерва).
      Выполняется при сбое на фазе Try или Confirm, возвращая систему в исходное состояние.

    Ключевые требования

    · Идемпотентность: повторный вызов Try, Confirm или Cancel должен давать тот же результат
    (защита от сетевых повторов).
    · Журналирование: обязательно сохранять состояние шагов для восстановления после падений
    (через сагу или таймеры).

    Где применяется

    · Платёжные системы: резервирование денег на счете (Try) → списание (Confirm) или возврат (Cancel).
    · Интернет-магазины: резерв товара на складе и блокировка средств на карте.
    · Бронирование: отели, авиабилеты.

    TCC vs Saga

    · TCC требует реализации трёх методов в каждом сервисе и подходит для коротких операций с
    жёсткой консистентностью.
    · Saga (цепочка событий) лучше для долгих процессов, но даёт лишь событийную согласованность
    (Eventual Consistency).

    Минусы TCC

    · Сложность реализации (нужна инфраструктура для таймаутов и анти-таймаутов).
    · Ограничения бизнес-логики (не все операции можно откатить, например, отправка email).
    · Риск «висячих» резервов при падении координатора.

     */
}
