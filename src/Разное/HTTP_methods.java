public class HTTP_methods {
    /*
    GET: Получение ресурса или списка (GET /users).
    POST: Создание нового ресурса (POST /users).
    PUT: Обновление/замена существующего ресурса (PUT /users/123).
    PATCH: Частичное обновление ресурса.
    DELETE: Удаление ресурса (DELETE /users/123).

    К идемпотентным относятся:

    GET — просто получение ресурса (не должен менять состояние)
    HEAD — то же, что GET, но без тела ответа
    PUT — полная замена ресурса (повторный PUT с тем же телом не меняет результат)
    DELETE — удаление ресурса (после первого удаления последующие не меняют состояние)
    OPTIONS — получение информации о возможностях сервера
    TRACE — диагностический метод (редко используется)

    Неидемпотентные:

    POST — обычно создаёт новый ресурс (каждый вызов может создавать что-то новое)
    PATCH — частичное обновление (может менять состояние по-разному при каждом вызове)

    200 OK: Успешный запрос.
    201 Created: Ресурс успешно создан.
    204 No Content: Успешно, ответ пуст (обычно для DELETE).
    400 Bad Request: Ошибка клиента (неверные данные).
    401 Unauthorized: Требуется авторизация.
    403 Forbidden: Авторизован, но нет доступа.
    404 Not Found: Ресурс не найден.
    500 Internal Server Error: Ошибка на стороне сервера.
     */
}
