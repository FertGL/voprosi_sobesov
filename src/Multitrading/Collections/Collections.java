package Multitrading.Collections;

public class Collections {
    /*
    ConcurrentHashMap — это потокобезопасная реализация интерфейса Map,
    предназначенная для использования в многопоточной среде. Она появилась в Java 5
    как альтернатива синхронизированным коллекциям.

    Java 8+
    -Отказ от сегментов в пользу более тонкой синхронизации.
    -Используется массив Node<K,V>[] + CAS (Compare-And-Swap) + synchronized
     только на конкретном бакете.
    -При коллизиях используются сбалансированные деревья (как в HashMap),
     если бакет становится слишком длинным.

    Ключевые особенности
    -Полная потокобезопасность без блокировки всей таблицы
    -Нет ConcurrentModificationException — итераторы работают с "снимком" данных на
     момент создания
    -Нет поддержки null — ни ключи, ни значения не могут быть null
    -Атомарные составные операции встроены в API
_________________________________________________________________________________________
    CopyOnWriteArrayList - Потокобезопасная альтернатива ArrayList,
    где все модифицирующие операции (add, set, remove) создают новую копию внутреннего массива.

    Внутри хранится обычный массив (volatile).

    При изменении:
    -Создается новая копия массива (длиной +1 для add, -1 для remove).
    -Вносятся изменения в копию.
    -Заменяется ссылка на старый массив новой (volatile гарантирует видимость).
    -При чтении используется текущий массив без блокировок.

    Ключевые особенности
    -Чтение никогда не блокируется и не требует синхронизации
    -Итераторы работают со снапшотом — не видят изменений после создания
    -Дорогостоящие записи — при каждом изменении копируется весь массив

    Идеально для:
    -Списков слушателей событий
    -Кэшей, которые редко обновляются
    -Сценариев с чтением >> записью
------------------------------------------------------------------------------------------
    CopyOnWriteArraySet - Потокобезопасная реализация Set, построенная на CopyOnWriteArrayList.

    Внутри используется CopyOnWriteArrayList.
    Уникальность элементов обеспечивается методами addIfAbsent и contains.
    При добавлении проверяет, есть ли уже элемент, и если нет — создает новую копию массива.

    Особенности
    -Наследует все свойства CopyOnWriteArrayList:
        -Быстрое чтение
        -Долгая запись
        -Итераторы не видят изменений
    -Подходит для маленьких множеств, которые редко меняются
    -Неупорядочен, но сохраняет порядок добавления (из-за ArrayList)

    Когда использовать?
    ConcurrentHashMap
    Всегда, когда нужен потокобезопасный Map
    Для счетчиков, кэшей, хранилищ ключ-значение
    Когда важна производительность записи

    CopyOnWriteArrayList
    Списки подписчиков/слушателей
    Данные конфигурации, которые обновляются редко
    Кэши с инвалидацией

    CopyOnWriteArraySet
    Маленькие множества с частым чтением
    Хранение уникальных слушателей
    Любой случай, где нужен Set с редкими изменениями
     */
}
