package Multitrading;

public class ThreadPools {
    /*
    Thread Pool (пул потоков) - это механизм управления потоками, который позволяет
    переиспользовать уже созданные потоки, что значительно повышает производительность
    приложения и уменьшает накладные расходы на создание новых потоков.

    1. FixedThreadPool (Фиксированный пул)
    Создает пул с фиксированным количеством потоков.
    Размер пула: Фиксированный
    Очередь: LinkedBlockedQueue
    Использование: CPU-bound задачи
    Когда использовать: Когда известно оптимальное количество потоков


    2. CachedThreadPool (Кэширующий пул)
    Создает потоки по мере необходимости и переиспользует их.
    Размер пула: Динамический
    Очередь: SynchronousQueue
    Использование: Много коротких задач
    Когда использовать: IO-bound, много быстрых операций


    3. SingleThreadExecutor (Одиночный пул)
    Пул с одним потоком, выполняет задачи последовательно.
    Размер пула: 1
    Очередь: LinkedBlockingQueue
    Использование: Последовательные задачи
    Когда использовать: Гарантия порядка выполнения


    4. ScheduledThreadPool (Планирующий пул)
    Для выполнения задач по расписанию.
    Размер пула: Фиксированный
    Очередь: DelayedWorkQueue
    Использование: Планирование
    Когда использовать: Задачи по расписанию


    5. WorkStealingPool (Пул с кражей работы)
    Использует ForkJoinPool для эффективного использования CPU.
    Размер пула: Динамический
    Очередь: Deque
    Использование: Параллельные рекурсивные задачи
    Когда использовать: Эффективное использование CPU


    6. ForkJoinPool (Пул для параллельных вычислений)
    Специализированный пул для задач типа ForkJoinTask.
    Размер пула: Динамический
    Очередь: WorkQueue
    Использование: Fork/Join задачи
    Когда использовать: Параллельные вычисления с разделением
     */
}
